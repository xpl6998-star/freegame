    'Sports': '体育',
    'Racing': '赛车',
    'Fighting': '格斗',
    'Card Game': '卡牌',
    'MOBA': '多人在线竞技',
    'Simulation': '模拟',
    'MMOFPS': '大型多人在线射击',
    'Social': '社交',
    'PVP': '玩家对战',
